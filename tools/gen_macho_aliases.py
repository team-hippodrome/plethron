"""Turn src/port/generated/zero_aliases.ld into inputs Apple's linker (ld64 / ld-prime) accepts.

ld64 reads no GNU linker scripts, so the decomp's alias names (tools/zero/gen_lift.py) become:
  - a plain alias "a = b;": a line "_b _a" of an -alias_list file (ld64 -alias_list), which defines _a at _b's
    address across objects and archives;
  - an alias into a lifted symbol "a = b + off;": an assembler .set in the translation unit that defines b, marked
    .alt_entry so the linker keeps it inside b's storage instead of splitting b at it; zero_lift_data.c is compiled
    through a wrapper that includes it and adds those lines (lift_data.c).
The wrapper also holds one pointer to each plain alias's target, so ld64 loads the archive member that defines it
(an -alias target alone does not pull a member out of libstadium_game.a).
The same idea as tools/gen_coff_aliases.py (MinGW); Linux and Android read zero_aliases.ld directly.

usage: gen_macho_aliases.py <zero_aliases.ld> <zero_lift_data.c> <out alias list> <out lift_data.c>
"""
import pathlib
import re
import sys

ld, lift_data, out_list, out_c = (pathlib.Path(p) for p in sys.argv[1:5])
script = re.sub(r'/\*.*?\*/', '', ld.read_text(encoding='utf-8'), flags=re.S)
lift_text = lift_data.read_text(encoding='utf-8')
plain, inner = [], []
for line in script.splitlines():
    line = line.strip()
    if not line:
        continue
    m = re.fullmatch(r'(\w+)\s*=\s*(\w+)\s*(?:\+\s*(\d+))?\s*;', line)
    if not m:
        raise SystemExit(f'{ld}: unexpected line: {line}')
    name, target, off = m.group(1), m.group(2), m.group(3)
    if off:
        if not re.search(r'ZLIFT_STORAGE\(%s,' % re.escape(target), lift_text):
            raise SystemExit(f'{ld}: {name} aliases into {target}, which {lift_data.name} does not define')
        inner.append((name, target, int(off)))
    else:
        plain.append((name, target))

out_list.parent.mkdir(parents=True, exist_ok=True)
text_list = ''.join(f'_{target} _{name}\n' for name, target in plain)
c = ['// Generated by tools/gen_macho_aliases.py: zero_lift_data.c plus the aliases into its symbols (macOS builds).',
     '#include "%s"' % lift_data.resolve().as_posix(), '__asm__(']
c += [f'    ".globl _{name}\\n.alt_entry _{name}\\n.set _{name}, _{target} + {off}\\n"' for name, target, off in inner]
# keep the plain aliases' targets linked (see above)
c += ['    ".section __DATA,__zalias_keep\\n.p2align 3\\n"']
c += [f'    ".quad _{target}\\n"' for target in sorted({t for _, t in plain})]
c += ['    ".text\\n"', ');']
text_c = '\n'.join(c) + '\n'
for path, text in ((out_list, text_list), (out_c, text_c)):
    if not path.exists() or path.read_text(encoding='utf-8') != text:  # unchanged: no rebuild
        path.write_text(text, encoding='utf-8')
