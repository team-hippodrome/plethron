#!/usr/bin/env python3
"""Writes src/port/collate_latin.inc: for U+00C0..U+024F the base letter(s), accent rank and case, and for the kana
U+3041..U+30FA the plain hiragana, voicing mark, small/katakana flags and vowel that src/port/collate.cpp sorts by
(Unicode data from Python's unicodedata, no game data).

    python3 tools/text/gen_collate_latin.py
"""
import os
import unicodedata as u

# Accent ranks, lowest first (close to the CLDR root order of the combining marks); collate.cpp's kMarkRank lists the
# same marks so text already in NFD sorts the same as precomposed letters.
MARKS = [0x301, 0x300, 0x306, 0x302, 0x30C, 0x30A, 0x308, 0x30B, 0x303, 0x307, 0x327, 0x328, 0x304, 0x323, 0x326,
         0x30F, 0x311, 0x31B, 0x335]
SPECIAL = {'ß': 'ss', 'ẞ': 'ss', 'æ': 'ae', 'Æ': 'ae', 'œ': 'oe', 'Œ': 'oe', 'ø': 'o', 'Ø': 'o', 'đ': 'd', 'Đ': 'd',
           'ł': 'l', 'Ł': 'l', 'þ': 'th', 'Þ': 'th', 'ð': 'd', 'Ð': 'd', 'ı': 'i', 'ħ': 'h', 'Ħ': 'h', 'ŧ': 't',
           'Ŧ': 't', 'ŀ': 'l', 'Ŀ': 'l', 'ĸ': 'q', 'ŉ': 'n', 'ſ': 's', 'ƀ': 'b', 'ƒ': 'f'}
STROKED = 'øØđĐłŁħĦŧŦƀ'


def main():
    out = []
    for cp in range(0xC0, 0x250):
        c = chr(cp)
        upper = 1 if c != c.lower() else 0
        if c in SPECIAL:
            b = SPECIAL[c]
            rank = MARKS.index(0x335) + 1 if c in STROKED else 0
        else:
            d = u.normalize('NFD', c)
            if not (len(d) >= 2 and d[0].isascii() and d[0].isalpha() and ord(d[1]) in MARKS):
                out.append('{0, 0, 0, 0}')
                continue
            b, rank = d[0].lower(), MARKS.index(ord(d[1])) + 1
        out.append("{'%s', %s, %d, %d}" % (b[0], "'%s'" % b[1] if len(b) > 1 else '0', rank, upper))
    path = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'port', 'collate_latin.inc')
    with open(path, 'w', newline='\n') as f:
        f.write('// Generated by tools/text/gen_collate_latin.py: {base, second base letter, accent rank, upper case}\n')
        f.write('// for U+00C0..U+024F. Do not edit.\n')
        for i in range(0, len(out), 4):
            f.write('    ' + ', '.join(out[i:i + 4]) + ', // U+%04X\n' % (0xC0 + i))
        f.write('// accent ranks: ' + ' '.join('%04X' % m for m in MARKS) + '\n')
        f.write('#define COLLATE_KANA_TABLE \\\n')
        f.write('    /* {plain hiragana, 1 dakuten / 2 handakuten, bit 0 small | bit 1 katakana, vowel a i u e o or 0} */ \\\n')
        rows = kana_rows()
        for i in range(0, len(rows), 6):
            f.write('    ' + ', '.join(rows[i:i + 6]) + ', /* U+%04X */ \\\n' % (0x3041 + i))
        f.write('\n')


def kana_rows():
    names = {u.name(chr(cp)): cp for cp in range(0x3041, 0x3097)}
    rows = []
    for cp in range(0x3041, 0x30FB):
        c = chr(cp)
        try:
            name = u.name(c)
        except ValueError:
            rows.append('{0, 0, 0, 0}')
            continue
        if not name.startswith(('HIRAGANA LETTER', 'KATAKANA LETTER')):
            rows.append('{0, 0, 0, 0}')
            continue
        d = u.normalize('NFD', c)
        base, voice = ord(d[0]), {0x3099: 1, 0x309A: 2}.get(ord(d[1]), 0) if len(d) > 1 else 0
        flags = 0
        if base >= 0x30A1:
            base -= 0x60
            flags |= 2
        bname = u.name(chr(base))
        if ' SMALL ' in bname:
            big = names.get(bname.replace('SMALL ', ''))
            if big is not None:
                base = big
                flags |= 1
        syl = u.name(chr(base)).split()[-1]
        vowel = syl[-1].lower() if syl[-1] in 'AIUEO' else ''
        rows.append("{0x%04X, %d, %d, %s}" % (base, voice, flags, "'%s'" % vowel if vowel else '0'))
    return rows


if __name__ == '__main__':
    main()
