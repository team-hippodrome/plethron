#!/usr/bin/env python3
"""Builds src/port/generated/port_fragment_entries.c for Stadium Zero: for every fragment, its ROM offset (the key
Fragment_Load is called with), its link address and the C function its header jumps to (fragment code is statically
linked in the port, so loading a fragment only has to find that function). Data blobs whose entry has no C
(models' tables in shared slots) get a NULL entry.

Usage: tools/zero/gen_fragment_entries.py <syms.json (read_maps.py)> <pokestadium0 checkout> <nm of libstadium_game.a> <out.c>
The jump word is read from the decomp build's linked image (build/production/fragmentNNN/fragmentNNN.bin): an
address, nothing else of the ROM.
"""
import json, struct, sys, pathlib

syms_p, dec, nm_p, out = sys.argv[1:5]
images = json.load(open(syms_p))
host_funcs = set()
for line in open(nm_p):
    p = line.split()
    if len(p) == 3 and p[1] == 'T':
        host_funcs.add(p[2])

rows = []
for name in sorted(n for n in images if n.startswith('fragment')):
    v = images[name]
    binp = pathlib.Path(dec) / 'build/production' / name / (name + '.bin')
    word = struct.unpack('>I', binp.read_bytes()[:4])[0]
    target = ((word & 0x03FFFFFF) << 2) | (v['vram'] & 0xF0000000)
    entry = None
    for n, a in sorted(v['defined'].items()):
        if a == target and n in host_funcs:
            entry = n
            break
    rows.append((v['rom'], v['vram'], entry, name, target))

with open(out, 'w') as f:
    w = f.write
    w('// Generated by tools/zero/gen_fragment_entries.py from the decomp\'s link maps and fragment header words.\n')
    w('#include <stddef.h>\n\n')
    for e in sorted({r[2] for r in rows if r[2]}):
        w('extern void %s();\n' % e)
    w('\nstruct PortFragmentEntry {\n    unsigned romStart;\n    unsigned textStart;\n    void* entry;\n    const char* name;\n};\n')
    w('const struct PortFragmentEntry gPortFragmentEntries[] = {\n')
    for rom, vram, entry, name, target in rows:
        w('    { 0x%08X, 0x%08X, %s, "%s" },%s\n' % (rom, vram, '(void*)' + entry if entry else 'NULL', name,
                                                     '' if entry else ' // entry 0x%08X has no C' % target))
    w('    { 0, 0, NULL, NULL },\n};\n')
    w('const unsigned gPortFragmentEntryCount = %d;\n' % len(rows))
missing = [r for r in rows if not r[2]]
print(len(rows), 'fragments,', len(missing), 'without a C entry:', ' '.join(r[3] for r in missing[:12]), '...' if len(missing) > 12 else '')
