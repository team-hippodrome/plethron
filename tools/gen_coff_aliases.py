"""Turn src/port/generated/zero_aliases.ld into sources a MinGW (COFF) link accepts.

ld.lld's COFF driver takes no linker scripts and no --defsym, so the decomp's alias names
(tools/zero/gen_lift.py) become:
  - a plain alias "a = b;": a COFF weak external with b as its default (.weak a / .set a, b), which resolves
    across objects and archives (aliases.S);
  - an alias into a lifted symbol "a = b + off;": an assembler .set in the translation unit that defines b, so
    zero_lift_data.c is compiled through a wrapper that includes it and adds those lines (lift_data.c).

usage: gen_coff_aliases.py <zero_aliases.ld> <zero_lift_data.c> <out aliases.S> <out lift_data.c>
"""
import pathlib
import re
import sys

ld, lift_data, out_s, out_c = (pathlib.Path(p) for p in sys.argv[1:5])
script = re.sub(r'/\*.*?\*/', '', ld.read_text(encoding='utf-8'), flags=re.S)
lift_text = lift_data.read_text(encoding='utf-8')
plain, inner = [], []
for line in script.splitlines():
    line = line.strip()
    if not line:
        continue
    m = re.fullmatch(r'(\w+)\s*=\s*(\w+)\s*(?:\+\s*(\d+))?\s*;', line)
    if not m:
        raise SystemExit(f'{ld}: unexpected line: {line}')
    name, target, off = m.group(1), m.group(2), m.group(3)
    if off:
        if not re.search(r'ZLIFT_STORAGE\(%s,' % re.escape(target), lift_text):
            raise SystemExit(f'{ld}: {name} aliases into {target}, which {lift_data.name} does not define')
        inner.append((name, target, int(off)))
    else:
        plain.append((name, target))

out_s.parent.mkdir(parents=True, exist_ok=True)
s = ['// Generated by tools/gen_coff_aliases.py from src/port/generated/zero_aliases.ld (MinGW builds).']
for name, target in plain:
    s += [f'.weak {name}', f'.set {name}, {target}']
text_s = '\n'.join(s) + '\n'
c = ['// Generated by tools/gen_coff_aliases.py: zero_lift_data.c plus the aliases into its symbols (MinGW builds).',
     '#include "%s"' % lift_data.resolve().as_posix(), '__asm__(']
c += [f'    ".globl {name}\\n.set {name}, {target} + {off}\\n"' for name, target, off in inner]
c += [');']
text_c = '\n'.join(c) + '\n'
for path, text in ((out_s, text_s), (out_c, text_c)):
    if not path.exists() or path.read_text(encoding='utf-8') != text:  # unchanged: no rebuild
        path.write_text(text, encoding='utf-8')
