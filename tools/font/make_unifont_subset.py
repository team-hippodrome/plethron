#!/usr/bin/env python3
"""Writes assets/font/unifont_subset.hex: the GNU Unifont glyphs of every character the translation tables and the
port's own screens use, in Unifont's .hex format (CODEPOINT:HEXBITS, 16 rows of 8 or 16 pixels).

The port draws translated text with these glyphs (src/port/unicode_font.c). Han characters and kana come from
unifont_jp (Japanese glyph shapes), everything else from unifont. Run it again after the tables gain characters:
    python3 tools/font/make_unifont_subset.py [--fonts /usr/share/fonts/opentype/unifont]
--check only reports characters missing from the committed subset (exit 1 when any are).

Unifont is dual licensed under the GNU GPL 2+ with the GNU font embedding exception and the SIL Open Font License 1.1
(assets/font/LICENSE-unifont.txt). No ROM data goes into this file.
"""
import argparse
import csv
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "assets", "font", "unifont_subset.hex")
TABLES = [os.path.join(ROOT, "translations", n) for n in ("ai.csv", "human.csv")]
TEXT_COLUMNS = ("ja", "en", "es", "de", "pt", "ko")
# Text the port draws itself, besides the tables: the language select screen (text_lookup.cpp kNames and prompt).
EXTRA = "にほんご 日本語 English Español Deutsch Português 한국어 Press C◀ for AI translations ?"


def wanted_chars():
    chars = set(chr(c) for c in range(0x20, 0x7F))
    chars.update(chr(c) for c in range(0xA0, 0x100))  # Latin-1: accents for es/de/pt
    chars.update(EXTRA)
    for path in TABLES:
        with open(path, newline="", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                for col in TEXT_COLUMNS:
                    chars.update(row.get(col) or "")
    return sorted(c for c in chars if c not in "\n\r\t")


def is_japanese(cp):
    return 0x3000 <= cp < 0x3100 or 0x4E00 <= cp < 0xA000 or 0x3400 <= cp < 0x4DC0 or 0xFF00 <= cp < 0xFFF0


def render(font, ch):
    width = int(round(font.getlength(ch)))
    if width not in (8, 16):
        return None
    img = Image.new("1", (width, 16), 0)
    draw = ImageDraw.Draw(img)
    draw.fontmode = "1"
    draw.text((0, 14), ch, font=font, fill=1, anchor="ls")  # Unifont's baseline is row 14
    if not ch.isspace() and img.getbbox() is None:
        return None
    rows = []
    for y in range(16):
        bits = 0
        for x in range(width):
            bits = (bits << 1) | (1 if img.getpixel((x, y)) else 0)
        rows.append(f"{bits:0{width // 4}X}")
    return "".join(rows)


def read_hex(path):
    glyphs = {}
    if os.path.exists(path):
        for line in open(path, encoding="ascii"):
            line = line.strip()
            if line and not line.startswith("#"):
                cp, bits = line.split(":")
                glyphs[int(cp, 16)] = bits
    return glyphs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fonts", default="/usr/share/fonts/opentype/unifont")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    chars = wanted_chars()
    if args.check:
        have = read_hex(OUT)
        missing = [c for c in chars if ord(c) not in have]
        print("missing:", "".join(missing) if missing else "none")
        return 1 if missing else 0
    base = ImageFont.truetype(os.path.join(args.fonts, "unifont.otf"), 16)
    jp = ImageFont.truetype(os.path.join(args.fonts, "unifont_jp.otf"), 16)
    out, missing = [], []
    for ch in chars:
        cp = ord(ch)
        bits = (render(jp, ch) if is_japanese(cp) else None) or render(base, ch)
        if bits is None:
            missing.append(ch)
            continue
        out.append(f"{cp:04X}:{bits}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("# GNU Unifont 15.1 subset (GPL-2.0+ with font embedding exception, or OFL-1.1): see LICENSE-unifont.txt\n")
        f.write("# Generated by tools/font/make_unifont_subset.py from translations/*.csv; do not edit by hand.\n")
        f.write("\n".join(out) + "\n")
    print(f"{len(out)} glyphs -> {os.path.relpath(OUT, ROOT)}" + (f"; no glyph for {''.join(missing)!r}" if missing else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
